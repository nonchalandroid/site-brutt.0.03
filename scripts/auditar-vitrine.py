#!/usr/bin/env python3
"""Valida metadados, imagens de compartilhamento e rastreadores no HTML público."""

import json
import re
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://tabacariabrutt.com.br"
TRACKERS = re.compile(r"googletagmanager\.com|google-analytics\.com|googleadservices\.com|connect\.facebook\.net|clarity\.ms", re.I)
EXAMPLES = re.compile(r"lorem ipsum|gerado por (?:ChatGPT|IA)|generated by (?:ChatGPT|AI)", re.I)


class Page(HTMLParser):
    def __init__(self, source):
        super().__init__()
        self.meta = {}
        self.canonical = ""
        self.title = ""
        self.schemas = []
        self.capture = None
        self.feed(source)

    def handle_starttag(self, tag, pairs):
        attrs = dict(pairs)
        if tag == "meta":
            self.meta[attrs.get("property") or attrs.get("name")] = attrs.get("content")
        if tag == "link" and attrs.get("rel") == "canonical":
            self.canonical = attrs.get("href", "")
        if tag == "title":
            self.capture = "title"
        if tag == "script" and attrs.get("type") == "application/ld+json":
            self.capture = "schema"

    def handle_data(self, data):
        if self.capture == "title":
            self.title += data
        if self.capture == "schema" and data.strip():
            self.schemas.append(json.loads(data))

    def handle_endtag(self, tag):
        if tag in {"title", "script"}:
            self.capture = None


def page_for(url):
    return ROOT / urlsplit(url).path.strip("/") / "index.html"


def main():
    sitemap = ElementTree.parse(ROOT / "sitemap.xml")
    indexed = {page_for(el.text): el.text for el in sitemap.findall(".//{*}loc")}
    aliases = {
        path: SITE + "/" + path.parent.name + "/"
        for path in ROOT.glob("*/index.html")
        if 'encodeURIComponent("' in path.read_text(encoding="utf-8")
        and 'location.replace("/?r="' in path.read_text(encoding="utf-8")
    }
    errors = []
    for path, url in (indexed | aliases).items():
        source = path.read_text(encoding="utf-8")
        try:
            page = Page(source)
        except ValueError as error:
            errors.append(f"{path.relative_to(ROOT)}: JSON-LD inválido ({error})")
            continue
        image = page.meta.get("og:image") or ""
        checks = {
            "title": page.title.strip(),
            "description": page.meta.get("description"),
            "canonical aponta para o sitemap": page.canonical in indexed.values(),
            "canonical próprio nas páginas indexáveis": path not in indexed or page.canonical == url,
            "Open Graph completo": all(page.meta.get("og:" + key) for key in ("title", "description", "type", "image")),
            "og:url corresponde à página": page.meta.get("og:url") == url,
            "imagem de compartilhamento existente": image.startswith(SITE + "/") and (ROOT / urlsplit(image).path.lstrip("/")).is_file(),
            "JSON-LD nas páginas indexáveis": path not in indexed or page.schemas,
            "HTML sem referências diretas a rastreadores": not TRACKERS.search(source),
            "HTML sem texto de exemplo conhecido": not EXAMPLES.search(source),
        }
        errors.extend(f"{path.relative_to(ROOT)}: {check}" for check, passed in checks.items() if not passed)
    if errors:
        raise SystemExit("\n".join(errors))
    print(f"{len(indexed)} páginas indexáveis e {len(aliases)} atalhos passaram nas verificações.")


if __name__ == "__main__":
    main()
